#!/bin/bash
# Turn the pinned armbian/rtl8723ds driver into a kernel patch for the Armbian
# rv1106 vendor kernel (6.1). Armbian's own driver harness adds this driver only
# for the rockchip64 and d1 families, so for rockchip-rv1106 we ship it as a userpatch.
# Does the same as driver_rtl8723DS() in armbian-build/lib/functions/compilation/patch/drivers_network.sh.
#
# Usage: make_rtl8723ds_patch.sh <kernel-tree> <rtl8723ds-tree> <out.patch>
#   kernel-tree    needs drivers/net/wireless/{Kconfig,Makefile} (sources/linux-rockchip-6.1)
#   rtl8723ds-tree armbian/rtl8723ds at the pinned commit (sources/rtl8723ds)
# Run in Linux/WSL (needs diff, sed).
set -euo pipefail

K=$(realpath "$1"); D=$(realpath "$2"); OUT=$3
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
W=drivers/net/wireless

mkdir -p "$T/a/$W" "$T/b/$W/rtl8723ds"
cp "$K/$W/Kconfig" "$K/$W/Makefile" "$T/a/$W/"
cp "$K/$W/Kconfig" "$K/$W/Makefile" "$T/b/$W/"

cp -R "$D"/{core,hal,include,os_dep,platform,Makefile,Kconfig} "$T/b/$W/rtl8723ds/"
sed -i 's/---help---/help/g' "$T/b/$W/rtl8723ds/Kconfig"
sed -i 's/^CONFIG_RTW_DEBUG.*/CONFIG_RTW_DEBUG = n/' "$T/b/$W/rtl8723ds/Makefile"
echo 'obj-$(CONFIG_RTL8723DS) += rtl8723ds/' >> "$T/b/$W/Makefile"
sed -i '/source "drivers\/net\/wireless\/ti\/Kconfig"/a source "drivers\/net\/wireless\/rtl8723ds\/Kconfig"' "$T/b/$W/Kconfig"
grep -q 'rtl8723ds/Kconfig' "$T/b/$W/Kconfig" || { echo "ti/Kconfig anchor not found" >&2; exit 1; }

commit=$(git -C "$D" rev-parse HEAD 2>/dev/null || echo unknown)
{
	echo "From: ShedNaja <noreply@shednaja>"
	echo "Subject: [PATCH] wireless: add Realtek RTL8723DS SDIO driver (armbian/rtl8723ds $commit)"
	echo
	echo "Kobra S1 host board: Wi-Fi is an RTL8723DS on SDIO. Generated by"
	echo "armbian_build/scripts/make_rtl8723ds_patch.sh, do not edit by hand."
	echo
	echo "---"
	# file timestamps stripped so the patch is reproducible
	(cd "$T" && diff -Nur a b) | sed -E 's/^((---|\+\+\+) [^\t]+)\t.*/\1/' || true
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
